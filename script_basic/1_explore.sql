-- the following is helping us understand the number of years of data available in our dataset
-- find the date of the first and last order
select 
min(order_date)::date first_order, 
max(order_date)::date last_order
from sales 

-- how many years of sales are available?
select 
min(order_date)::date first_order, 
max(order_date)::date last_order,
-- datediff(year,min(order_date)) order_range  --- sql query and not postgres
EXTRACT(YEAR FROM MAX(order_date)) - EXTRACT(YEAR FROM MIN(order_date)) AS order_range
from sales 


-- find the youngest and the oldest customer
select 
min(birthdate)::date youngest_b,
-- datediff(year, min(birthdate), getdate()) oldest_age,  -- sql command 
EXTRACT(YEAR FROM CURRENT_DATE) - EXTRACT(YEAR FROM MIN(birthdate)) AS oldest_age,
EXTRACT(YEAR FROM CURRENT_DATE) - EXTRACT(YEAR FROM MAX(birthdate)) AS youngest_age,
max(birthdate)::date oldest_b
from customers


