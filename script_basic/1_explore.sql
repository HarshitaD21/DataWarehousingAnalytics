-- Magnitude Analysis
Compare the measure values by categories.
It helps us understand the importance of different categories.
Aggregate[Measure] by Dimension 
ex: Total sales by country, total quantity by category, avg price by product, total orders by customer


-- Find the total customers by countries
select 
country,
count(customer_key) as total_cust
from customers
group by country
order by total_cust desc

-- find total customers by gender
select
gender,
count(customer_key)
from customers
group by gender

-- Find total products by category
select 
category,
count(product_key) total_prod
from products
group by category
order by total_prod desc

-- What is the avg costs in each category
select 
category,
round(avg(cost)) avg_cos
from products
group by category
order by avg_cos desc

-- What is the total revenue generated for each category
select 
p.category,
sum(s.sales_amount) category_revenue
from sales s
left join products p on p.product_key = s.product_key
group by p.category
order by category_revenue desc

-- Find total revenue is generated by each customer
select
c.customer_key,
c.first_name,
c.last_name,
sum(s.sales_amount) cust_spender
from sales s
left join customers c on c.customer_key = s.customer_key
group by c.customer_key,c.first_name, c.last_name
order by cust_spender desc 

-- What is the distribution of sold items across countries
select
c.country,
sum(s.quantity) total_sold_item
from sales s
left join customers c on c.customer_key = s.customer_key
group by c.country
order by total_sold_item desc


--Ranking Analysis - order the values of dimensions by measure. In order to identify top performers and bottom performers
formula: rank[dimension] by aggregated[measure]
ex: rank ountries by total sales, top 5 products by quantity, bottom 3 customers by total orders
we can use functions like rank, dense_rank, row_number

-- Which 5 products generate the highest revenue?
select 
p.product_name,
sum(s.sales_amount) category_revenue
from sales s
left join products p on p.product_key = s.product_key
group by p.product_name
order by category_revenue desc
limit 5 

-- the same thing which is above solved by using window functions
select *
from (       -- this is more complicated than the above solution but this is used when generating complex reports
    select 
    p.product_name,
    sum(s.sales_amount) category_revenue,
    row_number() over(order by sum(s.sales_amount) desc) rank_prod
    from sales s
    left join products p on p.product_key = s.product_key
    group by p.product_name
)
where rank_prod <=5

-- What are the 5 worst-performing products in terms of sales ?
select 
p.product_name,
sum(s.sales_amount) category_revenue
from sales s
left join products p on p.product_key = s.product_key
group by p.product_name
order by category_revenue
limit 5 

